static int same(const u8 *a,const u8 *b,u32 n) {u32 i;for(i=0;i<n;i++)if(a[i]!=b[i])return 0;return 1;}
static u32 le32(const u8 *p) { return (u32)p[0] | (u32)p[1]<<8 | (u32)p[2]<<16 | (u32)p[3]<<24; }
static u32 le16(const u8 *p) { return (u32)p[0] | (u32)p[1]<<8; }

/* Caller has validated/reserved all PT_LOAD destinations before this check. */
static int copied_kernel_matches(const u8 *src, u32 len) {
    u32 phoff, count, entsize, i, loads=0;
    if (len<52 || !same(src,(const u8 *)"\x7f" "ELF\1\1\1",7)) return 0;
    phoff=le32(src+28); entsize=le16(src+42); count=le16(src+44);
    if (entsize!=32 || !count || (u64)phoff+(u64)count*32>len) return 0;
    for (i=0;i<count;i++) {
        const u8 *p=src+phoff+i*32;
        u32 off, pa, filesz, memsz, j;
        const volatile u8 *dest;
        if (le32(p)!=1) continue;
        off=le32(p+4); pa=le32(p+12); filesz=le32(p+16); memsz=le32(p+20);
        if (!memsz || filesz>memsz || (u64)off+filesz>len ||
            (u64)pa+memsz>((u64)1<<32)) return 0;
        dest=(const volatile u8 *)(__UINTPTR_TYPE__)pa;
        for (j=0;j<filesz;j++) if (dest[j]!=src[off+j]) return 0;
        for (;j<memsz;j++) if (dest[j]!=0) return 0;
        ++loads;
    }
    return loads!=0;
}

/* Native bootinfo is count + physical pointer array followed by records.
 * Only the exact EFI+MEMMAP representation generated by our loader is
 * supported. Verify bounds before following either physical pointer. */
static int bootinfo_matches(u32 pa, const u8 *expected, u32 length) {
    const u8 *actual=(const u8 *)(__UINTPTR_TYPE__)pa;
    u32 maplen, count;
    __UINTPTR_TYPE__ ep=(__UINTPTR_TYPE__)expected;
    if (!expected || length<76 || length>16384 || (pa&3) ||
        (u64)pa+length>((u64)1<<32) || ep+length<ep ||
        ((u64)ep < (u64)pa+length && (u64)pa < (u64)ep+length)) return 0;
    if (le32(expected)!=2 || le32(expected+4)!=pa+12 || le32(expected+8)!=pa+44 ||
        le32(expected+12)!=32 || le32(expected+16)!=14 ||
        le32(expected+48)!=9) return 0;
    maplen=le32(expected+44); count=le32(expected+52);
    if (!count || maplen<32 || (u64)12+(u64)count*20!=maplen ||
        (u64)44+maplen!=length) return 0;
    return same(actual,expected,length);
}

/* Exact modified 11.1 installer; this is not a general NetBSD entry hook. */
int checkpoint_run(const void *source, u32 length, u32 bootinfo_pa,
                   u32 stack_top, int bda_writable_and_reserved,
                   const void *expected_bootinfo, u32 expected_length) {
    static const u8 expected_hash[32]={0xc0,0xbc,0x8c,0xeb,0x34,0xad,0x9b,0x5f,0x74,0xe1,0xef,0x1f,0xd6,0x08,0xfa,0xc2,0xfd,0x3d,0xa3,0x7b,0xd5,0x69,0x43,0x19,0x46,0x93,0xeb,0xd5,0x20,0x3a,0x4a,0xe6};
    static const u8 expected_code[13]={0x83,0xc4,0x04,0xe8,0xb8,0xba,0x02,0x00,0x83,0xc4,0x18,0x6a,0x02};
    volatile u8 *code=(volatile u8 *)(__UINTPTR_TYPE__)0x001001d0;
    volatile u8 *bda=(volatile u8 *)(__UINTPTR_TYPE__)0x472;
    u8 hash[32],saved[5],warm[2]; u32 i,displacement; int status;
    if(!source || !length || !bootinfo_pa || stack_top<16384 || (stack_top&3) || !bda_writable_and_reserved) return -1;
    sha256(source,length,hash); if(!same(hash,expected_hash,32)) return -1;
    if (!copied_kernel_matches(source,length) ||
        !bootinfo_matches(bootinfo_pa, expected_bootinfo, expected_length)) return -1;
    for(i=0;i<13;i++) if(code[i]!=expected_code[i]) return -1;
    for(i=0;i<5;i++) saved[i]=code[8+i];
    warm[0]=bda[0]; warm[1]=bda[1];
    displacement=(u32)(__UINTPTR_TYPE__)checkpoint_return-0x001001dd;
    code[8]=0xe9; for(i=0;i<4;i++)code[9+i]=(u8)(displacement>>(i*8));
    status=checkpoint_enter(0x00100000,stack_top,0x00020002,bootinfo_pa);
    for(i=0;i<5;i++) code[8+i]=saved[i];
    bda[0]=warm[0];bda[1]=warm[1];
    return status;
}
