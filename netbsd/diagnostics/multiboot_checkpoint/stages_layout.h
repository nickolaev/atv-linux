#ifndef ATV_STAGES_LAYOUT_H
#define ATV_STAGES_LAYOUT_H

#define STAGES_PHYSICAL_CODE 0x01c00000
#define STAGES_VIRTUAL_CODE 0xc0000000
#define STAGES_KERNEL_PT_OFFSET 0x3000
#define STAGES_ROWS 48
#define STAGES_TILES 7
#define STAGES_FB_OFFSET (ATV_FB_BASE & 0xfff)
#define STAGES_FB_PAGE (ATV_FB_BASE & ~0xfff)
#define STAGES_VIRTUAL_FB (STAGES_VIRTUAL_CODE + 0x1000 + STAGES_FB_OFFSET)
#define STAGES_MMIO_PAGES ((STAGES_FB_OFFSET + (STAGES_ROWS - 1) * ATV_FB_STRIDE + \
    ATV_FB_WIDTH * 4 + 0xfff) / 0x1000)

#ifndef ATV_FB_RED_OFFSET
#define ATV_FB_RED_OFFSET 16
#define ATV_FB_GREEN_OFFSET 8
#define ATV_FB_BLUE_OFFSET 0
#endif

#define STAGES_COLOR(r, g, b) (0xff000000 | ((r) << ATV_FB_RED_OFFSET) | \
    ((g) << ATV_FB_GREEN_OFFSET) | ((b) << ATV_FB_BLUE_OFFSET))

#endif
